# Bonus Task C — Format comparison table
# ---------------------------------------------------------------------------
def format_comparison_table(results: list[dict]) -> str:
    """
    Format a list of batch compare results as a readable Markdown table string.

    Args:
        results: List of dicts as returned by batch_compare.

    Returns:
        A beautiful Markdown table string with columns:
        | Prompt | Model | Response (truncated) | Latency | Tokens (In/Out) | Cost (USD) |
    """
    model_labels = {
        "gpt4o": "GPT-4o",
        "gpt4o_mini": "GPT-4o-mini",
        "gemini_flash": "Gemini 2.5 Flash",
    }

    def _clean(text: str, limit: int = 50) -> str:
        # Bỏ xuống dòng và dấu | để không làm vỡ bảng Markdown
        text = (text or "").replace("\n", " ").replace("|", "\\|").strip()
        return text if len(text) <= limit else text[:limit] + "..."

    lines = [
        "| Prompt | Model | Response (truncated) | Latency | Tokens (In/Out) | Cost (USD) |",
        "|---|---|---|---|---|---|",
    ]

    for item in results:
        prompt_text = _clean(item.get("prompt", ""))
        for key, label in model_labels.items():
            stats = item.get(key)
            if not stats:
                continue
            lines.append(
                f"| {prompt_text} | {label} | {_clean(stats['response'])} "
                f"| {stats['latency']:.2f}s "
                f"| {stats['input_tokens']}/{stats['output_tokens']} "
                f"| ${stats['cost']:.6f} |"
            )

    return "\n".join(lines)
